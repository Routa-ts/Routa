import { compareText } from "./contract-schemas.js";
import type { RouteMetadata } from "./project.js";
import { contractTypeReference, type ServiceContractMetadata } from "./services.js";

/**
 * Serializes the `.routa/testing.gen.ts` module: the project-bound `createTestApp`, the options
 * it accepts, and each scope's services factory type. It lists every module the application
 * loads as a lazy `import()`, so importing it runs no application code or factory.
 *
 * @param routes - The route metadata, as `.routa/routes.gen.ts` lists it
 * @param services - The application service contract, when `src/routa.ts` declares one
 */
export function testingModuleSource(
	routes: readonly RouteMetadata[],
	services: ServiceContractMetadata | undefined,
): string {
	const ordered = [...routes].sort(
		(left, right) => compareText(left.path, right.path) || compareText(left.file, right.file),
	);
	const scoped = ordered.filter((route) => route.services);
	const factories = [
		...(services ? [`\t"application": ApplicationServicesFactory<RoutaApplicationServices>;`] : []),
		...scoped.flatMap((route) => scopeFactories(route)),
	];
	const generatedTypes = [
		...(services ? ["RoutaApplicationServices"] : []),
		...(scoped.length > 0 ? ["RoutaFactoryCtxByPath"] : []),
	];
	const coreTypes = [
		...(services ? ["ApplicationServicesFactory"] : []),
		...(scoped.length > 0 ? ["RequestServicesFactory"] : []),
	];
	const parameter = services
		? `options?: TestAppOptions | ServicesFactory<"application">`
		: "options?: TestAppOptions";

	return `// Generated by Routa.
// Safe to edit, but regeneration may update this file after preview.
// Source: src/routa.ts and src/routes directory

${coreTypes.length > 0 ? `import type { ${coreTypes.join(", ")} } from "@routa-ts/core";\n` : ""}import {
	createTestApplication,
	type ProjectModules,
	type TestApplication,
} from "@routa-ts/core/testing";
${generatedTypes.length > 0 ? `import type { ${generatedTypes.join(", ")} } from "./routes.gen.js";\n` : ""}
/**
 * The services factory a scope declares, by scope: \`"application"\`, a route file's path, or a
 * method and path such as \`"POST /orders"\`. Annotate a factory declared on its own with it.
 */
export type ServicesFactory<TScope extends keyof RoutaServicesFactories> =
	RoutaServicesFactories[TScope];

type RoutaServicesFactories = ${factories.length > 0 ? `{\n${factories.join("\n")}\n}` : "{}"};

/** Factories that replace whole service scopes before a test application is built. */
export type TestAppOptions = {
	readonly services?: ${services ? `ServicesFactory<"application">` : "never"};
	readonly routes?: ${scoped.length > 0 ? `{\n${scoped.map(routeOptions).join("\n")}\n\t}` : "never"};
};

const modules: ProjectModules = {
${projectModules(ordered)
	.map(
		(file) => `\t${JSON.stringify(file)}: () => import(${JSON.stringify(moduleSpecifier(file))}),`,
	)
	.join("\n")}
};

/**
 * Builds an isolated, in-memory instance of this project, with its own services and cleanup.
 * Each factory in \`options\` replaces its scope's factory before construction, so the original
 * never runs; omitted scopes keep their factories. Call \`dispose()\` when the test ends.
 */
export function createTestApp(
	${parameter},
): Promise<TestApplication> {
	return createTestApplication(modules, options);
}
`;
}

/** The factory types a route file declares: its own, then each method's. */
function scopeFactories(route: RouteMetadata): string[] {
	const { routeFile, methods = {} } = route.services ?? {};
	const path = JSON.stringify(route.path);
	const factory = (contract: ServiceContractMetadata, scope: string) =>
		`RequestServicesFactory<${contractTypeReference(contract)}, RoutaFactoryCtxByPath[${path}][${JSON.stringify(scope)}]>`;

	return [
		...(routeFile ? [`\t${path}: ${factory(routeFile, "routeFile")};`] : []),
		...Object.keys(methods)
			.sort(compareText)
			.map(
				(method) =>
					`\t${JSON.stringify(`${method.toUpperCase()} ${route.path}`)}: ${factory(methods[method]!, method)};`,
			),
	];
}

/** The replacement options for one route file: its services, then its methods'. */
function routeOptions(route: RouteMetadata): string {
	const { routeFile, methods = {} } = route.services ?? {};
	const methodNames = Object.keys(methods).sort(compareText);
	const entries = [
		...(routeFile
			? [`\t\t\treadonly services?: ServicesFactory<${JSON.stringify(route.path)}>;`]
			: []),
		...(methodNames.length > 0
			? [
					`\t\t\treadonly methods?: {\n${methodNames
						.map(
							(method) =>
								`\t\t\t\treadonly ${method}?: { readonly services?: ServicesFactory<${JSON.stringify(`${method.toUpperCase()} ${route.path}`)}> };`,
						)
						.join("\n")}\n\t\t\t};`,
				]
			: []),
	];

	return `\t\treadonly ${JSON.stringify(route.path)}?: {\n${entries.join("\n")}\n\t\t};`;
}

/** Every module the application loads: the metadata, the config, route files, and middleware. */
function projectModules(routes: readonly RouteMetadata[]): string[] {
	const files = new Set([".routa/routes.gen.ts", "src/routa.ts"]);

	for (const route of routes) {
		files.add(route.file);

		for (const middleware of [route.middleware, ...Object.values(route.methodMiddleware)].flat()) {
			// The route file's own middleware arrives through its route config.
			if (middleware.file !== route.file) {
				files.add(middleware.file);
			}
		}
	}

	return [...files].sort(compareText);
}

/** The specifier `.routa/testing.gen.ts` imports a project module through. */
function moduleSpecifier(file: string): string {
	const emitted = file.replace(/\.ts$/, ".js");
	return emitted.startsWith(".routa/") ? `./${emitted.slice(".routa/".length)}` : `../${emitted}`;
}
