/**
 * Reads the requested route reference output format from CLI arguments.
 *
 * @param argv - Command-line arguments after `routes`
 * @returns The requested format, or `undefined` when the format is invalid
 */
function routeReferenceFormat(argv: readonly string[]): RouteReferenceFormat | undefined {
	const formatArg = argv.find((item) => item.startsWith("--format"));

	if (!formatArg) {
		return "markdown";
	}

	const value = formatArg.includes("=")
		? formatArg.slice(formatArg.indexOf("=") + 1)
		: argv[argv.indexOf(formatArg) + 1];

	return value === "json" || value === "markdown" ? value : undefined;
}

/**
 * Projects route metadata into a public route reference shape.
 *
 * @param routes - Validated route metadata
 * @returns Route reference data suitable for JSON or Markdown rendering
 */
function routeReference(
	routes: readonly RouteMetadata[],
	authentication: AuthenticationMetadata | undefined,
): RouteReference {
	return {
		routes: [...routes]
			.sort(
				(left, right) => compareText(left.path, right.path) || compareText(left.file, right.file),
			)
			.map((route) => ({
				path: route.path,
				file: route.file,
				groups: route.groups,
				segments: route.segments,
				methods: [...route.methods]
					.sort(compareText)
					.map((method) => routeReferenceMethod(route, method, authentication)),
			})),
	};
}

/**
 * Builds a method-level route reference entry.
 *
 * @param route - Route metadata that owns the method
 * @param method - Uppercase HTTP method name
 * @returns Method metadata with resolved middleware, context, rejects, inputs, and responses
 */
function routeReferenceMethod(
	route: RouteMetadata,
	method: string,
	authentication: AuthenticationMetadata | undefined,
): RouteReferenceMethod {
	const key = method.toLowerCase();
	const middleware = route.methodMiddleware[key] ?? route.middleware;
	const ctx = Array.from(new Set(middleware.flatMap((item) => item.provides))).sort();
	const rejects = uniqueRejects([
		...(authentication
			? [
					{
						type: "authenticationFailed",
						status: 401,
						description: authenticationFailedDescription,
					},
				]
			: []),
		...(rejectsAmbiguousCredentials(middleware, authentication)
			? [
					{
						type: "ambiguousCredentials",
						status: 400,
						description: ambiguousCredentialsDescription,
					},
				]
			: []),
		...middleware.flatMap((item) => item.rejects),
	]);

	return {
		method,
		inputs: route.inputs[key] ?? { ...emptyRouteInputs },
		responses: [...(route.responses[key] ?? [])].sort((left, right) => left - right),
		ctx,
		rejects,
		middleware: middleware.map((item) => ({
			file: item.file,
			name: item.name,
			requires: item.requires,
			provides: item.provides,
			rejects: item.rejects,
		})),
	};
}

/**
 * Renders validated route metadata as a Markdown route reference.
 *
 * @param routes - Validated route metadata
 * @returns Markdown route reference
 */
function routeReferenceMarkdown(
	routes: readonly RouteMetadata[],
	authentication: AuthenticationMetadata | undefined,
): string {
	const reference = routeReference(routes, authentication);
	const lines = ["# Routa Route Reference", ""];

	if (reference.routes.length === 0) {
		lines.push("No routes found.", "");
		return lines.join("\n");
	}

	for (const route of reference.routes) {
		lines.push(`## ${route.path}`, "", `File: \`${route.file}\``);

		if (route.groups.length > 0) {
			lines.push(`Groups: ${route.groups.map((item) => `\`${item}\``).join(", ")}`);
		}

		if (route.segments.length > 0) {
			lines.push(`Segments: ${route.segments.map((item) => `\`${item}\``).join(", ")}`);
		}

		lines.push("");

		for (const method of route.methods) {
			lines.push(
				`### ${method.method}`,
				"",
				`Inputs: ${inputList(method.inputs).join(", ") || "none"}`,
				`Responses: ${method.responses.join(", ") || "none"}`,
				`Context: ${method.ctx.map((item) => `\`ctx.${item}\``).join(", ") || "none"}`,
				`Rejects: ${method.rejects.map((item) => `\`${item.type}\` (${item.status})`).join(", ") || "none"}`,
				"",
				"Middleware:",
			);

			if (method.middleware.length === 0) {
				lines.push("- none");
			} else {
				for (const middleware of method.middleware) {
					lines.push(
						`- \`${middleware.name}\` from \`${middleware.file}\``
							+ `; requires: ${middleware.requires.join(", ") || "none"}`
							+ `; provides: ${middleware.provides.join(", ") || "none"}`
							+ `; rejects: ${middleware.rejects.map((item) => `${item.type}:${item.status}`).join(", ") || "none"}`,
					);
				}
			}

			lines.push("");
		}
	}

	return `${lines.join("\n")}\n`;
}

/**
 * Converts input metadata into a compact list of declared input locations.
 *
 * @param inputs - Route method input metadata
 * @returns Declared input location names
 */
function inputList(inputs: RouteMethodInputMetadata): string[] {
	return (["params", "query", "headers", "cookies", "body"] as const).filter((key) => inputs[key]);
}

function uniqueRejects(rejects: readonly MiddlewareRejectMetadata[]): MiddlewareRejectMetadata[] {
	const unique = new Map<string, MiddlewareRejectMetadata>();

	for (const reject of rejects) {
		unique.set(reject.type, reject);
	}

	return Array.from(unique.values()).sort((left, right) => compareText(left.type, right.type));
}

type RouteDiscovery = {
	routes: RouteMetadata[];
	diagnostics: Diagnostic[];
};

/**
 * Discovers route metadata from a Routa project's route files.
 *
 * @param cwd - Project root directory
 * @returns The discovered route metadata for each `route.ts` file under `src/routes`, plus discovery diagnostics
 */
function discoverRoutes(
	cwd: string,
	parser: ts.SourceFileParser,
	authentication: AuthenticationMetadata | undefined,
): RouteDiscovery {
	const routesDir = join(cwd, routesRoot);

	if (!existsSync(routesDir)) {
		return { routes: [], diagnostics: [] };
	}

	const sources = walk(routesDir);
	const files = sources.filter(isRouteFile);
	const folders = new Map<string, FolderMiddleware>();
	const folderMiddleware = (file: string) => {
		const parsed = folders.get(file) ?? parseMiddlewareFile(cwd, file, parser, authentication);
		folders.set(file, parsed);
		return parsed.middleware;
	};
	const diagnostics: Diagnostic[] = [];

	for (const file of sources.filter((item) => basename(item) === "middleware.ts")) {
		folderMiddleware(relative(cwd, file));
	}

	const routes = files.flatMap((file) => {
		const relativeFile = relative(cwd, file);
		const rawSegments = rawRouteSegments(routesDir, file);
		const groups = rawSegments.filter(
			(segment) => segment.startsWith("(") && segment.endsWith(")"),
		);
		const segments = rawSegments.filter(
			(segment) => !(segment.startsWith("(") && segment.endsWith(")")),
		);
		const middlewareFiles = folderMiddlewareFiles(cwd, rawSegments);
		const inheritedMiddleware = middlewareFiles.flatMap(folderMiddleware);
		const routeFileMiddleware = parseRouteFileMiddleware(cwd, relativeFile, parser, authentication);
		const middleware = [...inheritedMiddleware, ...routeFileMiddleware.route];
		const methodMiddleware = Object.fromEntries(
			Object.entries(routeFileMiddleware.methods).map(([method, items]) => [
				method,
				[...middleware, ...items],
			]),
		);
		const path = routePathForFile(routesDir, file);
		const parsed = parseRouteContract(file, parser);

		if (!parsed.configFound) {
			diagnostics.push({
				code: "ROUTA_ROUTE_CONFIG_UNRESOLVED",
				severity: "error",
				message: `Route config in ${relativeFile} could not be resolved.`,
				file: relativeFile,
				routePath: path,
				suggestion: `Export a route config created by createRouteRoot(${JSON.stringify(path)}).`,
			});
			return [];
		}

		if (parsed.explicitOptions) {
			diagnostics.push({
				code: "ROUTA_OPTIONS_AUTOMATIC",
				severity: "error",
				message: `OPTIONS ${path} must not be declared explicitly.`,
				file: relativeFile,
				routePath: path,
				suggestion:
					"Remove the options contract. Routa generates OPTIONS and its Allow header from the path's declared methods.",
			});
		}

		const contract = parsed.contract;
		const services = routeServices(cwd, relativeFile, parser);
		diagnostics.push(...services.diagnostics.map((item) => ({ ...item, routePath: path })));
		const ctx = Array.from(
			new Set([
				...middleware.flatMap((item) => item.provides),
				...Object.values(methodMiddleware).flatMap((items) =>
					items.flatMap((item) => item.provides),
				),
			]),
		).sort();

		diagnostics.push(
			...routeFileMiddleware.diagnostics.map((item) => ({ ...item, routePath: path })),
		);

		for (const unresolved of routeFileMiddleware.unresolved) {
			diagnostics.push({
				code: "ROUTA_MIDDLEWARE_UNRESOLVED",
				severity: "error",
				message: `Middleware ${unresolved} cannot be statically resolved, so it would run without contract checks.`,
				file: relativeFile,
				routePath: path,
				suggestion:
					"Reference middleware as a direct identifier of a createMiddleware export, and list entries explicitly instead of spreading arrays.",
			});
		}

		for (const [method, metadata] of Object.entries(contract)) {
			diagnostics.push(...outcomeRuleDiagnostics(method, metadata.outcomes, relativeFile, path));
		}

		return [
			{
				file: relativeFile,
				path,
				methods: Object.keys(contract).map((method) => method.toUpperCase()),
				responses: Object.fromEntries(
					Object.entries(contract).map(([method, metadata]) => [
						method,
						methodResponseStatuses(
							// Every operation can fail authentication once credentials are resolved.
							authentication
								? [
										...metadata.responses,
										401,
										...(rejectsAmbiguousCredentials(
											methodMiddleware[method] ?? middleware,
											authentication,
										)
											? [400]
											: []),
									]
								: metadata.responses,
							methodMiddleware[method] ?? middleware,
						),
					]),
				),
				inputs: Object.fromEntries(
					Object.entries(contract).map(([method, metadata]) => [method, metadata.inputs]),
				),
				...(Object.values(contract).some((metadata) => metadata.deprecation)
					? {
							deprecations: Object.fromEntries(
								Object.entries(contract).flatMap(([method, metadata]) =>
									metadata.deprecation ? [[method, metadata.deprecation]] : [],
								),
							),
						}
					: {}),
				middleware,
				methodMiddleware,
				...(authentication && { middlewareFiles }),
				...(services.services && { services: services.services }),
				ctx,
				groups,
				segments,
			},
		];
	});

	// A guard two folders re-export from one module is reported once, where its call is written.
	const folderDiagnostics = new Map(
		[...folders.values()]
			.flatMap((folder) => folder.diagnostics)
			.map((item) => [`${item.code}\0${item.file}\0${item.message}`, item]),
	);

	return { routes, diagnostics: [...folderDiagnostics.values(), ...diagnostics] };
}

function isRouteFile(file: string): boolean {
	const name = basename(file);
	return (
		name === "route.ts"
		|| (name.endsWith(".ts")
			&& name !== "middleware.ts"
			&& name !== "schemas.ts"
			&& !name.endsWith(".test.ts"))
	);
}

function flatRouteSegments(file: string): string[] {
	return file.slice(0, -".ts".length).split(".");
}

function rawRouteSegments(routesDir: string, file: string): string[] {
	const relativeRouteDir = relative(routesDir, dirname(file));
	const directorySegments = relativeRouteDir === "" ? [] : relativeRouteDir.split(sep);

	return [
		...directorySegments,
		...(basename(file) === "route.ts" ? [] : flatRouteSegments(basename(file))),
	];
}

function routePathForFile(routesDir: string, file: string): string {
	const segments = rawRouteSegments(routesDir, file)
		.filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")))
		.map((segment) => (segment.startsWith("$") ? `:${segment.slice(1)}` : segment));

	return `/${segments.join("/")}`.replace(/\/$/, "") || "/";
}

/**
 * Reads whether `src/routa.ts` may turn lifecycle headers on.
 *
 * Lifecycle headers are a tuning-backed feature: a literal `false` or an omitted key keeps them
 * off, and any other value counts as possibly enabled. A configuration the source cannot be read
 * for the key, such as a variable, a call, a spread, or a computed key, counts the same way.
 * Generation never executes application modules, so ownership diagnostics apply to every
 * configuration the source can produce.
 */
function lifecycleHeadersEnabled(cwd: string, parser: ts.SourceFileParser): boolean {
	const file = join(cwd, "src/routa.ts");

	if (!existsSync(file)) {
		return false;
	}

	const sourceFile = parseTypeScriptFile(file, parser);
	let foundCall = false;
	let enabled = false;
	const visit = (node: ts.Node): void => {
		if (ts.isCallExpression(node) && callName(node.expression) === "createRouta") {
			foundCall = true;
			enabled ||= configMayEnableLifecycleHeaders(node.arguments[0]);
		}

		ts.forEachChild(node, visit);
	};

	visit(sourceFile);
	const hasDefaultExport = sourceFile.statements.some(
		(statement) =>
			(ts.isExportAssignment(statement) && !statement.isExportEquals)
			|| (ts.isExportDeclaration(statement)
				&& statement.exportClause
				&& ts.isNamedExports(statement.exportClause)
				&& statement.exportClause.elements.some((element) => element.name.text === "default")),
	);
	return enabled || (!foundCall && hasDefaultExport);
}

/** Walks a config in source order, so a later literal `false` overrides what a spread may hold. */
function configMayEnableLifecycleHeaders(argument: ts.Expression | undefined): boolean {
	if (!argument) {
		return false;
	}

	const config = objectLiteral(argument);

	if (!config) {
		return true;
	}

	let enabled = false;

	for (const member of config.properties) {
		if (ts.isSpreadAssignment(member) || ts.isComputedPropertyName(member.name)) {
			enabled = true;
		} else if (propertyName(member.name) === "lifecycleHeaders") {
			enabled =
				!ts.isPropertyAssignment(member)
				|| unwrapExpression(member.initializer).kind !== ts.SyntaxKind.FalseKeyword;
		}
	}

	return enabled;
}

function methodResponseStatuses(
	routeStatuses: readonly number[],
	middleware: readonly MiddlewareMetadata[],
): number[] {
	return Array.from(
		new Set([
			...routeStatuses,
			...middleware.flatMap((item) => item.rejects.map((reject) => reject.status)),
		]),
	).sort((left, right) => left - right);
}

/**
 * Reports outcome declarations that HTTP or the route method forbids: terminal 1xx
 * statuses, body schemas on 204, 205, 304 and every HEAD outcome, and 304 outside GET and HEAD.
 *
 * TypeScript rejects the same declarations first. This covers what it cannot see, such as
 * the method a contract is registered under or a contract built outside the route config.
 */
function outcomeRuleDiagnostics(
	method: string,
	outcomes: readonly ResponseOutcomeDeclaration[],
	file: string,
	routePath: string,
): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];
	const label = `${method.toUpperCase()} ${routePath}`;

	for (const { name, status, hasSchema } of outcomes) {
		if (status === undefined) {
			continue;
		}

		if (status >= 100 && status < 200) {
			diagnostics.push({
				code: "ROUTA_RESPONSE_INFORMATIONAL_STATUS",
				severity: "error",
				message: `Outcome "${name}" on ${label} uses informational status ${status}, which cannot be a terminal route outcome.`,
				file,
				routePath,
				suggestion: "Use a final status from 200 to 599.",
			});
		}

		if (hasSchema && (status === 204 || status === 205 || status === 304)) {
			diagnostics.push({
				code: "ROUTA_RESPONSE_BODYLESS_SCHEMA",
				severity: "error",
				message: `Outcome "${name}" on ${label} declares a schema, but status ${status} has no body.`,
				file,
				routePath,
				suggestion: "Remove the schema and return no data, or choose a status that carries a body.",
			});
		} else if (hasSchema && method === "head") {
			diagnostics.push({
				code: "ROUTA_RESPONSE_BODYLESS_SCHEMA",
				severity: "error",
				message: `Outcome "${name}" on ${label} declares a schema, but HEAD responses have no body.`,
				file,
				routePath,
				suggestion: "Remove the schema and return no data from HEAD outcomes.",
			});
		}

		if (status === 304 && method !== "get" && method !== "head") {
			diagnostics.push({
				code: "ROUTA_RESPONSE_NOT_MODIFIED_METHOD",
				severity: "error",
				message: `Outcome "${name}" on ${label} uses status 304, which is valid only for GET and HEAD.`,
				file,
				routePath,
				suggestion: "Use a different status, or move the outcome to a GET or HEAD route.",
			});
		}
	}

	return diagnostics;
}

/**
 * Reports route methods that do not declare a 2xx success response.
 *
 * DELETE methods are included and may satisfy the check with a 204 response.
 *
 * @param routes - Route metadata to inspect
 * @returns Diagnostics for route methods missing a declared 2xx response
 */
function missingSuccessResponseDiagnostics(routes: RouteMetadata[]): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		for (const [method, statuses] of Object.entries(route.responses)) {
			if (!statuses.some((status) => status >= 200 && status < 300)) {
				diagnostics.push({
					code: "ROUTA_MISSING_SUCCESS_RESPONSE",
					severity: "error",
					message: `${method.toUpperCase()} ${route.path} is missing a 2xx success response.`,
					file: route.file,
					routePath: route.path,
					suggestion:
						method === "delete"
							? "Add a declared success response with a 2xx HTTP status (204 is allowed)."
							: "Add a declared success response with a 2xx HTTP status.",
				});
			}
		}
	}

	return diagnostics;
}

/**
 * Reports duplicate schema export names in route schema files.
 *
 * @param cwd - Project root directory
 * @returns Diagnostics for repeated `export const` names in route `schemas.ts` files under `src/routes`
 */
function duplicateSchemaDiagnostics(cwd: string, parser: ts.SourceFileParser): Diagnostic[] {
	const routesDir = join(cwd, routesRoot);

	if (!existsSync(routesDir)) {
		return [];
	}

	const diagnostics: Diagnostic[] = [];

	for (const file of walk(routesDir).filter((item) => item.endsWith(`${sep}schemas.ts`))) {
		const relativeFile = relative(cwd, file);
		const sourceFile = parseTypeScriptFile(file, parser);
		const seen = new Set<string>();

		for (const statement of sourceFile.statements) {
			if (!ts.isVariableStatement(statement)) {
				continue;
			}

			if (!statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
				continue;
			}

			if (!(statement.declarationList.flags & ts.NodeFlags.Const)) {
				continue;
			}

			for (const declaration of statement.declarationList.declarations) {
				if (!ts.isIdentifier(declaration.name)) {
					continue;
				}

				const name = declaration.name.text;

				if (seen.has(name)) {
					diagnostics.push({
						code: "ROUTA_DUPLICATE_SCHEMA_NAME",
						severity: "error",
						message: `Duplicate schema export ${name}.`,
						file: relativeFile,
						suggestion: "Use a stable contract-purpose name such as CreateUserResponse.",
					});
					continue;
				}

				seen.add(name);
			}
		}
	}

	return diagnostics;
}

function runResultShapeDiagnostics(cwd: string, parser: ts.SourceFileParser): Diagnostic[] {
	const srcDir = join(cwd, "src");

	if (!existsSync(srcDir)) {
		return [];
	}

	return walk(srcDir)
		.filter((file) => file.endsWith(".ts"))
		.flatMap((file) => runResultShapeDiagnosticsForFile(cwd, relative(cwd, file), file, parser));
}

function runResultShapeDiagnosticsForFile(
	cwd: string,
	relativeFile: string,
	file: string,
	parser: ts.SourceFileParser,
): Diagnostic[] {
	const sourceFile = parseTypeScriptFile(file, parser);
	const diagnostics: Diagnostic[] = [];

	// Middleware declared through a helper bound to `createMiddleware<Requirements>()` is checked
	// like a direct `createMiddleware` call.
	function contractKind(call: ts.CallExpression): "route" | "middleware" | undefined {
		const name = callName(call.expression);

		if (name === "createRoute") {
			return "route";
		}

		return name === "createMiddleware"
			|| (ts.isIdentifier(unwrapExpression(call.expression))
				&& middlewareRequirement(cwd, relativeFile, call.expression, parser) !== undefined)
			? "middleware"
			: undefined;
	}

	function visit(node: ts.Node): void {
		const kind =
			ts.isCallExpression(node)
			&& node.arguments[0] !== undefined
			&& ts.isObjectLiteralExpression(node.arguments[0])
				? contractKind(node)
				: undefined;

		if (kind && ts.isCallExpression(node) && node.arguments[0] !== undefined) {
			const contract = node.arguments[0] as ts.ObjectLiteralExpression;
			const run = objectProperty(contract, "run");
			const resultTypes =
				kind === "route"
					? contractObjectKeys(contract, "responses")
					: contractObjectKeys(contract, "rejects");

			if (run) {
				diagnostics.push(
					...runReturnObjectDiagnostics(
						cwd,
						sourceFile,
						relativeFile,
						run.initializer,
						resultTypes,
					),
				);
			}
		}

		ts.forEachChild(node, visit);
	}

	visit(sourceFile);
	return diagnostics;
}

function runReturnObjectDiagnostics(
	cwd: string,
	sourceFile: ts.SourceFile,
	file: string,
	run: ts.Expression,
	resultTypes: Set<string> | undefined,
): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];

	function checkReturn(expression: ts.Expression): void {
		const object = objectLiteral(expression);

		if (!object) {
			return;
		}

		for (const property of objectProperties(object)) {
			const name = propertyName(property.name);

			if (!name || name === "type" || name === "data" || name === "headers" || name === "cookies") {
				continue;
			}

			const position = sourceFile.getLineAndCharacterOfPosition(property.name.getStart(sourceFile));
			diagnostics.push({
				code: "ROUTA_RESULT_SHAPE",
				severity: "error",
				message: `Run result includes unsupported field "${name}". Route and middleware results may only include "type", "data", "headers", and "cookies".`,
				file: `${file}:${position.line + 1}:${position.character + 1}`,
				suggestion: `Remove "${name}" from the returned result object.`,
			});
		}

		const typeProperty = objectProperty(object, "type");
		const typeExpression = typeProperty ? unwrapExpression(typeProperty.initializer) : undefined;

		if (
			resultTypes
			&& typeProperty
			&& typeExpression
			&& ts.isStringLiteralLike(typeExpression)
			&& !resultTypes.has(typeExpression.text)
		) {
			const position = sourceFile.getLineAndCharacterOfPosition(
				typeProperty.initializer.getStart(sourceFile),
			);
			const options = [...resultTypes].map((type) => `"${type}"`).join(", ");
			diagnostics.push({
				code: "ROUTA_RESULT_TYPE",
				severity: "error",
				message: `Run result type "${typeExpression.text}" is not declared.`,
				file: `${file}:${position.line + 1}:${position.character + 1}`,
				suggestion: options
					? `Use one of the declared result types: ${options}.`
					: "Declare this result type before returning it.",
			});
		}
	}

	function visit(node: ts.Node): void {
		if (ts.isReturnStatement(node) && node.expression) {
			checkReturn(node.expression);
		}

		if (
			(ts.isArrowFunction(run) || ts.isFunctionExpression(run))
			&& run.body === node
			&& ts.isExpression(node)
		) {
			checkReturn(node);
		}

		ts.forEachChild(node, visit);
	}

	if (ts.isArrowFunction(run) || ts.isFunctionExpression(run)) {
		visit(run.body);
	}

	return diagnostics.map((diagnostic) => ({
		...diagnostic,
		file: diagnostic.file?.startsWith(cwd) ? relative(cwd, diagnostic.file) : diagnostic.file,
	}));
}

function contractObjectKeys(
	contract: ts.ObjectLiteralExpression,
	name: string,
): Set<string> | undefined {
	const property = objectProperty(contract, name);
	const object = objectLiteral(property?.initializer);

	if (!object) {
		return;
	}

	return new Set(
		objectProperties(object).flatMap((item) => {
			const key = propertyName(item.name);
			return key ? [key] : [];
		}),
	);
}

/**
 * Lists the folder `middleware.ts` files a route inherits middleware from, root first.
 *
 * @param cwd - Project root directory
 * @param rawSegments - Route path segments used to locate nested `middleware.ts` files
 * @returns The root routes `middleware.ts` and each nested one that exists, relative to `cwd`
 */
function folderMiddlewareFiles(cwd: string, rawSegments: string[]): string[] {
	const candidates = [`${routesRoot}/middleware.ts`];
	let current = routesRoot;

	for (const segment of rawSegments) {
		current = join(current, segment);
		candidates.push(join(current, "middleware.ts"));
	}

	return candidates.filter((file) => existsSync(join(cwd, file)));
}

