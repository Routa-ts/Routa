/**
 * Validates middleware ordering for each route.
 *
 * @returns Diagnostics for middleware that requires context before it has been provided.
 */
function middlewareOrderDiagnostics(routes: RouteMetadata[], authenticated: boolean): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		const chains =
			route.methods.length > 0
				? route.methods.map(
						(item) => route.methodMiddleware[item.toLowerCase()] ?? route.middleware,
					)
				: [route.middleware];

		for (const chain of chains) {
			// Credential orchestration resolves ctx.auth before the first middleware runs, and Routa
			// gives every middleware the request identity and logger.
			const provided = new Set<string>([
				...(authenticated ? ["auth"] : []),
				"requestId",
				"correlationId",
				"logger",
			]);

			for (const middleware of chain) {
				for (const required of middleware.requires) {
					if (!provided.has(required)) {
						diagnostics.push({
							code: "ROUTA_MIDDLEWARE_ORDER",
							severity: "error",
							message: `${middleware.name} requires ctx.${required} before it is provided.`,
							file: middleware.file,
							routePath: route.path,
							suggestion: `Move middleware that provides ${required} before ${middleware.name}.`,
						});
					}
				}

				for (const providedField of middleware.provides) {
					provided.add(providedField);
				}
			}
		}
	}

	return diagnostics;
}

/**
 * Reports middleware context Routa cannot accept: `ctx.services`, `ctx.requestId`,
 * `ctx.correlationId`, and `ctx.logger`, which it reserves, whether provided or passed to
 * `next()`, `provides` it cannot read from source, and a requirement interface it cannot read.
 *
 * @param routes - Route metadata whose middleware chains are checked, each contract once
 */
function middlewareContextDiagnostics(
	routes: RouteMetadata[],
	authenticated: boolean,
): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];
	const seen = new Set<ts.ObjectLiteralExpression>();
	const provided = { ...reservedContext, ...(authenticated && { auth: reservedAuthContext }) };

	for (const route of routes) {
		for (const item of [route.middleware, ...Object.values(route.methodMiddleware)].flat()) {
			const source = middlewareContract(item);

			if (!source || seen.has(source.contract)) {
				continue;
			}

			seen.add(source.contract);
			diagnostics.push(...source.requirementDiagnostics);
			const report = (code: string, message: string, suggestion: string) =>
				diagnostics.push({ code, severity: "error", message, file: source.file, suggestion });
			const passed = nextPayloadKeys(source.contract);

			if (source.providesUnresolved) {
				report(
					"ROUTA_MIDDLEWARE_PROVIDES_UNRESOLVED",
					`Middleware ${item.name} declares provides that cannot be statically read.`,
					"Declare provides as an object literal, or a const object literal it names, with a plain key for each schema and no spreads.",
				);
			}

			for (const [key, { reason, advice }] of Object.entries(provided)) {
				if (item.provides.includes(key)) {
					report(
						"ROUTA_CONTEXT_RESERVED",
						`Middleware ${item.name} provides ctx.${key}, which Routa reserves for ${reason}.`,
						advice,
					);
				}
			}

			for (const [key, { reason, advice }] of Object.entries(reservedContext)) {
				if (passed.includes(key)) {
					report(
						"ROUTA_CONTEXT_RESERVED",
						`Middleware ${item.name} passes ctx.${key} to next(), which Routa reserves for ${reason}.`,
						advice,
					);
				}
			}
		}
	}

	return diagnostics;
}

/**
 * The keys of every object a middleware's `run` passes to its own `next` continuation: an object
 * literal written in the call, or a `const` object literal the call names. A call to a nested
 * function that rebinds the continuation's name is not the continuation.
 */
function nextPayloadKeys(contract: ts.ObjectLiteralExpression): string[] {
	const run = runFunction(contract);
	const parameter = run?.parameters[0]?.name;
	const continuation = parameter && continuationName(parameter);

	if (!run || !continuation) {
		return [];
	}

	const keys: string[] = [];
	const visit = (node: ts.Node): void => {
		if (node !== run && isFunctionNode(node) && rebinds(node, continuation)) {
			return;
		}

		// A block that declares its own binding of the name calls that binding, not the continuation.
		if (
			ts.isBlock(node)
			&& node.parent !== run
			&& "binding" in continuation
			&& blockDeclares(node, continuation.binding)
		) {
			return;
		}

		if (ts.isCallExpression(node) && callsContinuation(node.expression, continuation)) {
			keys.push(...payloadKeys(run, payloadObject(run, node.arguments[0]), 0));
		}

		ts.forEachChild(node, visit);
	};

	visit(run);
	return keys;
}

/** Whether a block's own statements declare `name`, as a variable, function, or class. */
function blockDeclares(block: ts.Block, name: string): boolean {
	return block.statements.some((statement) =>
		ts.isVariableStatement(statement)
			? statement.declarationList.declarations.some((declaration) =>
					bindsName(declaration.name, name),
				)
			: (ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement))
				&& statement.name?.text === name,
	);
}

/** The keys an object payload names, including those of spreads `payloadObject` can read. */
function payloadKeys(
	run: RunFunction,
	payload: ts.ObjectLiteralExpression | undefined,
	depth: number,
): string[] {
	if (!payload || depth > 8) {
		return [];
	}

	return payload.properties.flatMap((property) => {
		if (ts.isSpreadAssignment(property)) {
			return payloadKeys(run, payloadObject(run, property.expression), depth + 1);
		}

		const name =
			ts.isPropertyAssignment(property) || ts.isShorthandPropertyAssignment(property)
				? propertyName(property.name)
				: undefined;

		return name === undefined ? [] : [name];
	});
}

type RunFunction = ts.ArrowFunction | ts.FunctionExpression | ts.MethodDeclaration;

/** The middleware's `run`, written as a property or as a method. */
function runFunction(contract: ts.ObjectLiteralExpression): RunFunction | undefined {
	const method = contract.properties.find(
		(property): property is ts.MethodDeclaration =>
			ts.isMethodDeclaration(property) && propertyName(property.name) === "run",
	);
	const value = method ?? propertyValue(contract, "run");
	const run = value && ts.isExpression(value) ? unwrapExpression(value) : value;

	return run
		&& (ts.isArrowFunction(run) || ts.isFunctionExpression(run) || ts.isMethodDeclaration(run))
		? run
		: undefined;
}

/**
 * How `run` reaches its continuation: the local name `{ next }` destructures it to, or the
 * parameter whose `next` member it calls.
 */
function continuationName(
	parameter: ts.BindingName,
): { binding: string } | { member: string } | undefined {
	if (ts.isIdentifier(parameter)) {
		return { member: parameter.text };
	}

	if (!ts.isObjectBindingPattern(parameter)) {
		return;
	}

	for (const element of parameter.elements) {
		const key = element.propertyName ? propertyName(element.propertyName) : undefined;

		const local = element.name && ts.isIdentifier(element.name) ? element.name.text : undefined;

		if ((key ?? local) === "next") {
			return local === undefined ? undefined : { binding: local };
		}
	}
}

function callsContinuation(
	callee: ts.Expression,
	continuation: { binding: string } | { member: string },
): boolean {
	if ("binding" in continuation) {
		return ts.isIdentifier(callee) && callee.text === continuation.binding;
	}

	return (
		ts.isPropertyAccessExpression(callee)
		&& ts.isIdentifier(callee.expression)
		&& callee.expression.text === continuation.member
		&& ts.isIdentifier(callee.name)
		&& callee.name.text === "next"
	);
}

type FunctionNode =
	| ts.ArrowFunction
	| ts.FunctionExpression
	| ts.FunctionDeclaration
	| ts.MethodDeclaration;

function isFunctionNode(node: ts.Node): node is FunctionNode {
	return (
		ts.isArrowFunction(node)
		|| ts.isFunctionExpression(node)
		|| ts.isFunctionDeclaration(node)
		|| ts.isMethodDeclaration(node)
	);
}

/** Whether a nested function's own name or parameters shadow the continuation's name. */
function rebinds(
	fn: FunctionNode,
	continuation: { binding: string } | { member: string },
): boolean {
	const name = "binding" in continuation ? continuation.binding : continuation.member;
	const bound = (binding: ts.BindingName): boolean =>
		ts.isIdentifier(binding)
			? binding.text === name
			: binding.elements.some(
					(element) => "name" in element && element.name !== undefined && bound(element.name),
				);

	return (
		(!ts.isArrowFunction(fn)
			&& fn.name !== undefined
			&& ts.isIdentifier(fn.name)
			&& fn.name.text === name)
		|| fn.parameters.some((item) => bound(item.name))
	);
}

/** The object a continuation call passes, written in the call or named by a `const` in `run`. */
function payloadObject(
	run: RunFunction,
	argument: ts.Expression | undefined,
): ts.ObjectLiteralExpression | undefined {
	const written = objectLiteral(argument);

	if (written || !argument) {
		return written;
	}

	const payload = unwrapExpression(argument);

	if (!ts.isIdentifier(payload)) {
		return;
	}

	// The `const` the call can see: the one declared in the nearest enclosing block within `run`,
	// so a same-named `const` in another block never stands in for the payload.
	for (let scope: ts.Node | undefined = payload.parent; scope; scope = scope.parent) {
		// A function between the call and `run` that binds the name as a parameter shadows any
		// outer `const`; what that parameter holds is not statically known.
		if (
			scope !== run
			&& (ts.isArrowFunction(scope)
				|| ts.isFunctionExpression(scope)
				|| ts.isFunctionDeclaration(scope)
				|| ts.isMethodDeclaration(scope))
			&& scope.parameters.some((parameter) => bindsName(parameter.name, payload.text))
		) {
			return;
		}

		// A loop or catch binding between the call and `run` also shadows an outer `const`.
		if (
			(ts.isForOfStatement(scope) || ts.isForInStatement(scope) || ts.isForStatement(scope))
			&& scope.initializer
			&& ts.isVariableDeclarationList(scope.initializer)
			&& scope.initializer.declarations.some((declaration) =>
				bindsName(declaration.name, payload.text),
			)
		) {
			return;
		}

		if (
			ts.isCatchClause(scope)
			&& scope.variableDeclaration
			&& bindsName(scope.variableDeclaration.name, payload.text)
		) {
			return;
		}

		if (ts.isBlock(scope)) {
			for (const statement of scope.statements) {
				if (ts.isVariableStatement(statement)) {
					const isConst = (statement.declarationList.flags & ts.NodeFlags.Const) !== 0;

					for (const declaration of statement.declarationList.declarations) {
						if (bindsName(declaration.name, payload.text)) {
							// Only a `const` object literal is known; a `let` or `var` may hold anything.
							return isConst && ts.isIdentifier(declaration.name)
								? objectLiteral(declaration.initializer)
								: undefined;
						}
					}
				}
			}
		}

		if (scope === run) {
			return;
		}
	}

	return;
}

/** Whether a parameter's binding, destructured or not, declares `name`. */
function bindsName(binding: ts.BindingName, name: string): boolean {
	if (ts.isIdentifier(binding)) {
		return binding.text === name;
	}

	return binding.elements.some(
		(element) =>
			ts.isBindingElement(element) && element.name !== undefined && bindsName(element.name, name),
	);
}

function middlewareRejectStatusDiagnostics(routes: RouteMetadata[]): Diagnostic[] {
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		for (const middleware of [
			...route.middleware,
			...Object.values(route.methodMiddleware).flat(),
		]) {
			for (const reject of middleware.rejects) {
				if (reject.status >= 400 && reject.status <= 599) {
					continue;
				}

				diagnostics.push({
					code: "ROUTA_MIDDLEWARE_REJECT_STATUS",
					severity: "error",
					message: `${middleware.name} reject "${reject.type}" uses non-error status ${reject.status}.`,
					file: middleware.file,
					routePath: route.path,
					suggestion: "Middleware rejects must use a 4xx or 5xx HTTP status.",
				});
			}
		}
	}

	return diagnostics;
}

/**
 * Reports routes that share the same path.
 *
 * @param routes - The discovered route metadata to inspect.
 * @returns Diagnostics for each duplicate route path.
 */
/**
 * Reports a service name that more than one scope combined for a request declares: the
 * application, the route file, and one method. Unrelated route files and methods may reuse names.
 */
function serviceCollisionDiagnostics(
	routes: RouteMetadata[],
	application: ServiceContractMetadata | undefined,
): Diagnostic[] {
	type Scope = { owner: string; contract: ServiceContractMetadata };
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		const { routeFile, methods = {} } = route.services ?? {};
		const applicationScope: Scope[] = application
			? [{ owner: "the application services in src/routa.ts", contract: application }]
			: [];
		const routeFileScope: Scope[] = routeFile
			? [{ owner: "the route file's services", contract: routeFile }]
			: [];
		const scopes = [
			...routeFileScope.map((scope) => ({ ...scope, earlier: applicationScope })),
			...Object.entries(methods).map(([method, contract]) => ({
				owner: `the ${method.toUpperCase()} services`,
				contract,
				earlier: [...applicationScope, ...routeFileScope],
			})),
		];

		for (const { owner, contract, earlier } of scopes) {
			for (const name of contract.names) {
				const first = earlier.find((scope) => scope.contract.names.includes(name));

				if (first) {
					diagnostics.push({
						code: "ROUTA_SERVICES_DUPLICATE",
						severity: "error",
						message: `Service "${name}" is declared by ${first.owner} and by ${owner}, which run in one request.`,
						file: route.file,
						routePath: route.path,
						suggestion:
							"Rename one of the services. Services combined for one request need distinct names; unrelated route files and methods may reuse a name.",
					});
				}
			}
		}
	}

	return diagnostics;
}

/**
 * Reports middleware that requires a service its placement does not provide. Filesystem
 * middleware sees application services, route-file middleware also its route file's, and method
 * middleware also its method's. A name only a later factory builds is still unavailable.
 */
function serviceRequirementDiagnostics(
	routes: RouteMetadata[],
	application: ServiceContractMetadata | undefined,
): Diagnostic[] {
	const fixes = {
		filesystem: (name: string) =>
			`Filesystem middleware sees only application services. Declare ${name} in the application services, or move the middleware into a route file or method that declares it.`,
		"route-file": (name: string) =>
			`Route-file middleware sees application and route-file services. Declare ${name} in one of them, or move the middleware into a method that declares it.`,
		method: (name: string) =>
			`Method middleware sees application, route-file, and method services. Declare ${name} in one of them.`,
	};
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		for (const placement of requirementPlacements(route)) {
			const { middleware } = placement;
			const available = new Set(
				[application, ...placement.scopes].flatMap((scope) => scope?.names ?? []),
			);

			for (const name of middleware.requiresServices.names) {
				if (available.has(name)) {
					continue;
				}

				const later = placement.later.find((scope) => scope.contract.names.includes(name));
				diagnostics.push({
					code: "ROUTA_SERVICES_UNAVAILABLE",
					severity: "error",
					message: `${placement.kind} middleware ${middleware.name} requires service ${JSON.stringify(name)}, which ${placement.where} does not provide before it runs.${
						later ? ` ${later.owner} declare it, but their factory runs after this middleware.` : ""
					}`,
					file: middleware.file,
					routePath: route.path,
					suggestion: fixes[placement.position](JSON.stringify(name)),
				});
			}
		}
	}

	return diagnostics;
}

/** One middleware that requires services, where it runs in a route's chains. */
type RequirementPlacement = {
	middleware: MiddlewareMetadata & { requiresServices: ServiceContractMetadata };
	position: "filesystem" | "route-file" | "method";
	/** Names the position in messages: `Filesystem`, `Route-file`, or the method, such as `POST`. */
	kind: string;
	/** Names the middleware and its placement, such as `withCache on POST /orders`. */
	label: string;
	/** The route, or route and method, it runs on, such as `/orders` or `POST /orders`. */
	where: string;
	/** The request-scoped contracts built before it runs, in order. */
	scopes: ReadonlyArray<ServiceContractMetadata | undefined>;
	/** The request-scoped contracts the same request builds after it runs. */
	later: ReadonlyArray<{ owner: string; contract: ServiceContractMetadata }>;
};

/**
 * Lists a route's middleware that require services, with the scopes built before and after each.
 * Filesystem and route-file middleware run for every method, so each appears once per route.
 */
function requirementPlacements(route: RouteMetadata): RequirementPlacement[] {
	const { routeFile, methods = {} } = route.services ?? {};
	const methodScopes = Object.entries(methods)
		.sort(([left], [right]) => compareText(left, right))
		.map(([method, contract]) => ({ owner: `The ${method.toUpperCase()} services`, contract }));
	const routeFileScope = routeFile
		? [{ owner: "The route file's services", contract: routeFile }]
		: [];
	const placements: RequirementPlacement[] = [];
	const add = (
		chain: readonly MiddlewareMetadata[],
		placement: Omit<RequirementPlacement, "middleware" | "label">,
		label: (middleware: MiddlewareMetadata) => string,
	) => {
		for (const middleware of chain) {
			if (middleware.requiresServices) {
				placements.push({
					...placement,
					middleware: { ...middleware, requiresServices: middleware.requiresServices },
					label: label(middleware),
				});
			}
		}
	};

	add(
		route.middleware.filter((item) => item.file !== route.file),
		{
			position: "filesystem",
			kind: "Filesystem",
			where: route.path,
			scopes: [],
			later: [...routeFileScope, ...methodScopes],
		},
		(item) => `${item.name} in ${item.file}`,
	);
	add(
		route.middleware.filter((item) => item.file === route.file),
		{
			position: "route-file",
			kind: "Route-file",
			where: route.path,
			scopes: [routeFile],
			later: methodScopes,
		},
		(item) => `${item.name} on ${route.path}`,
	);

	for (const method of route.methods.map((item) => item.toLowerCase())) {
		const where = `${method.toUpperCase()} ${route.path}`;
		add(
			(route.methodMiddleware[method] ?? route.middleware).slice(route.middleware.length),
			{
				position: "method",
				kind: method.toUpperCase(),
				where,
				scopes: [routeFile, methods[method]],
				later: [],
			},
			(item) => `${item.name} on ${where}`,
		);
	}

	return placements;
}

function duplicateRouteDiagnostics(routes: RouteMetadata[]): Diagnostic[] {
	const seen = new Map<string, RouteMetadata>();
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		const previous = seen.get(route.path);

		if (previous) {
			diagnostics.push({
				code: "ROUTA_DUPLICATE_ROUTE",
				severity: "error",
				message: `Duplicate route path ${route.path}.`,
				file: route.file,
				routePath: route.path,
				suggestion: `Rename or move ${route.file}; it conflicts with ${previous.file}.`,
			});
			continue;
		}

		seen.set(route.path, route);
	}

	return diagnostics;
}

/**
 * Reports routes whose generated OpenAPI operationIds collide.
 *
 * The id comes from the method and path, and paths such as `/users/:id` and
 * `/users/id` spell the same words, so they can still produce one id.
 */
function duplicateOperationIdDiagnostics(routes: RouteMetadata[]): Diagnostic[] {
	const seen = new Map<string, string>();
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		for (const method of Object.keys(route.responses)) {
			const id = operationId(method, toOpenApiPath(route.path));
			const previous = seen.get(id);

			if (!previous) {
				seen.set(id, `${method.toUpperCase()} ${route.path}`);
				continue;
			}

			diagnostics.push({
				code: "ROUTA_DUPLICATE_OPERATION_ID",
				severity: "error",
				message: `${method.toUpperCase()} ${route.path} and ${previous} would both generate the OpenAPI operationId ${id}.`,
				file: route.file,
				routePath: route.path,
				suggestion:
					"Rename a path segment so the two routes differ by more than punctuation or parameter syntax. Routa generates operationIds from the method and path.",
			});
		}
	}

	return diagnostics;
}

function deprecationReplacementDiagnostics(routes: RouteMetadata[]): Diagnostic[] {
	const paths = new Set(routes.map((route) => route.path));
	const diagnostics: Diagnostic[] = [];

	for (const route of routes) {
		for (const [method, deprecation] of Object.entries(route.deprecations ?? {})) {
			if (!deprecation) continue;
			const replacement = deprecation.replacement;
			if (!replacement) continue;

			if (replacement.startsWith("/")) {
				if (!paths.has(replacement)) {
					diagnostics.push({
						code: "ROUTA_DEPRECATION_REPLACEMENT_ROUTE_NOT_FOUND",
						severity: "error",
						message: `${method.toUpperCase()} ${route.path} deprecation replacement ${replacement} is not a Routa route.`,
						file: route.file,
						routePath: route.path,
						suggestion:
							"Use an existing local path beginning with /, or an absolute http(s) URL for another API.",
					});
				}
				continue;
			}

			if (!isExternalApiUrl(replacement)) {
				diagnostics.push({
					code: "ROUTA_DEPRECATION_REPLACEMENT_URL_INVALID",
					severity: "error",
					message: `${method.toUpperCase()} ${route.path} deprecation replacement must be an existing local path or absolute http(s) URL.`,
					file: route.file,
					routePath: route.path,
					suggestion:
						"Use /new-route for this API, or https://api.example.com/new-route for another API.",
				});
			}
		}
	}

	return diagnostics;
}

function isExternalApiUrl(value: string): boolean {
	try {
		const url = new URL(value);
		return url.protocol === "http:" || url.protocol === "https:";
	} catch {
		return false;
	}
}

/**
 * Serializes route metadata into the `.routa/routes.gen.ts` module source.
 *
 * This is the single source of truth for the generated metadata shape; both
 * `routa check` and `routa scaffold` emit it so the runtime always loads the
 * same structure.
 *
 * @param routes - The route metadata to serialize.
 * @param services - The application service contract, when `src/routa.ts` declares one.
 * @param authentication - The authentication contract, when `src/routa.ts` declares one.
 * @param correlationHeader - The header `src/routa.ts` reads correlation from, when it is on.
 * @returns The generated TypeScript source.
 */
export function routesMetadataSource(
	routes: RouteMetadata[],
	services?: ServiceContractMetadata,
	authentication?: AuthenticationMetadata,
	correlationHeader?: string,
): string {
	const orderedRoutes = [...routes].sort(
		(left, right) => compareText(left.path, right.path) || compareText(left.file, right.file),
	);
	const servicesSource = services
		? `export const routaApplicationServices = ${JSON.stringify(services.names, null, "\t")} as const;

export type RoutaApplicationServices = ${contractTypeReference(services)};

`
		: "";
	const names = authentication?.schemes.map((scheme) => scheme.name) ?? [];
	const authenticationSource = authentication
		? `export const routaAuthenticationSchemes = ${JSON.stringify(names, null, "\t")} as const;

export const routaMultipleCredentials = ${JSON.stringify(authentication.multipleCredentials)} as const;

/** The principal schema's output, from the authentication config in \`src/routa.ts\`. */
export type RoutaPrincipal = import("@routa-ts/core").PrincipalOf<typeof import("../src/routa.js").default>;

export type RoutaAuthenticationScheme = ${names.map((name) => JSON.stringify(name)).join(" | ")};

/** \`ctx.auth\` on an operation no requireAuth guard protects. */
export type RoutaAuth = import("@routa-ts/core").AuthContext<RoutaAuthenticationScheme, RoutaPrincipal>;

`
		: "";
	const correlationSource = correlationHeader
		? `/** The header \`src/routa.ts\` reads correlation from, which startup checks against it. */
export const routaCorrelationHeader = ${JSON.stringify(correlationHeader)};

`
		: "";
	return `${generatedHeader}export const routaRoutes = ${JSON.stringify(orderedRoutes, null, "\t")} as const;

${servicesSource}${authenticationSource}${correlationSource}${routeContextTypes(orderedRoutes, services !== undefined, authentication)}
`;
}

/**
 * Writes the generated project state: route metadata to `.routa/routes.gen.ts` and the test
 * application module to `.routa/testing.gen.ts`. Unchanged files are not rewritten.
 *
 * @param cwd - The project root directory.
 * @param routes - The discovered route metadata to serialize.
 * @param services - The application service contract, when `src/routa.ts` declares one.
 */
function writeGeneratedState(
	cwd: string,
	routes: RouteMetadata[],
	services: ServiceContractMetadata | undefined,
	authentication: AuthenticationMetadata | undefined,
	correlationHeader: string | undefined,
): void {
	const routesFile = join(cwd, ".routa/routes.gen.ts");
	const previous = existsSync(routesFile) ? readFileSync(routesFile, "utf8") : undefined;
	writeGeneratedFile(
		routesFile,
		routesMetadataSource(routes, services, authentication, correlationHeader),
	);

	try {
		writeGeneratedFile(join(cwd, ".routa/testing.gen.ts"), testingModuleSource(routes, services));
	} catch (error) {
		// Keep the two files describing the same routes: put the previous route table back.
		if (previous === undefined) {
			rmSync(routesFile, { force: true });
		} else {
			writeFileSync(routesFile, previous);
		}

		throw error;
	}
}

function writeGeneratedFile(file: string, source: string): void {
	if (existsSync(file) && readFileSync(file, "utf8") === source) {
		return;
	}

	mkdirSync(dirname(file), { recursive: true });
	writeFileSync(file, source);
}

/**
 * Builds TypeScript declarations for route context types and module registration.
 *
 * @returns Generated source text for per-route context types, route-to-method context maps, and the `@routa-ts/core` module augmentation.
 */
function routeContextTypes(
	routes: RouteMetadata[],
	application: boolean,
	authentication: AuthenticationMetadata | undefined,
): string {
	const ctxTypes = routes
		.map((route) => {
			const typeName = routeCtxTypeName(route);
			const ctx =
				route.ctx.length > 0
					? route.ctx.map((key) => `\t${JSON.stringify(key)}: unknown;`).join("\n")
					: "\treadonly __empty?: never;";

			return `export type ${typeName} = {\n${ctx}\n};`;
		})
		.join("\n\n");

	const ctxMap = `export type RoutaRouteCtxByPath = {\n${routes
		.map(
			(route) =>
				`\t${JSON.stringify(route.path)}: ${routeMethodCtxMap(route, application, authentication)};`,
		)
		.join("\n")}\n};`;
	const ctxByKey = `export type RoutaCtxByKey = ${ctxByKeyType(routes, authentication)};`;
	const scoped = routes.filter((route) => route.services);
	const factoryCtx =
		scoped.length > 0
			? `\n\nexport type RoutaFactoryCtxByPath = {\n${scoped
					.map(
						(route) =>
							`\t${JSON.stringify(route.path)}: ${factoryCtxMap(route, application, authentication)};`,
					)
					.join("\n")}\n};`
			: "";

	const requirementChecks = serviceRequirementChecks(routes, application);
	const servicesRegistration = `${
		application ? "\t\tapplicationServices: RoutaApplicationServices;\n" : ""
	}${scoped.length > 0 ? "\t\tfactoryCtxByPath: RoutaFactoryCtxByPath;\n" : ""}${
		authentication
			? "\t\tauthentication: { schemes: RoutaAuthenticationScheme; principal: RoutaPrincipal };\n"
			: ""
	}`;

	return `${ctxTypes}\n\n${ctxMap}${factoryCtx}${requirementChecks}\n\n${ctxByKey}\n\ndeclare module "@routa-ts/core" {\n\texport interface Register {\n\t\trouteCtxByPath: RoutaRouteCtxByPath;\n\t\tctxByKey: RoutaCtxByKey;\n${servicesRegistration}\t}\n}`;
}

/**
 * Builds the context each of a route file's services factories receives: the context of the
 * middleware before it and the services of earlier scopes. The route file's factory follows the
 * filesystem middleware; each method's follows the route file's own middleware too.
 */
function factoryCtxMap(
	route: RouteMetadata,
	application: boolean,
	authentication: AuthenticationMetadata | undefined,
): string {
	const { routeFile, methods = {} } = route.services ?? {};
	const filesystem = route.middleware.filter((item) => item.file !== route.file);
	const entries = [
		...(routeFile
			? [
					`\t\trouteFile: ${ctxObjectType(filesystem, servicesType(application, []), authType(filesystem, authentication))};`,
				]
			: []),
		...Object.keys(methods)
			.sort(compareText)
			.map(
				(method) =>
					`\t\t${method}: ${ctxObjectType(route.middleware, servicesType(application, [routeFile]), authType(route.middleware, authentication))};`,
			),
	];

	return `{\n${entries.join("\n")}\n\t}`;
}

/**
 * Builds one type-level check for each placement of a middleware that requires services: the
 * services available where it runs must satisfy its requirement interface, so `tsc` reports an
 * incompatible service at that placement. Each placement is checked on its own, so unrelated
 * scopes may give one name different types. Projects without such middleware get no checks.
 */
function serviceRequirementChecks(routes: RouteMetadata[], application: boolean): string {
	const checks = new Set<string>();

	for (const route of routes) {
		for (const placement of requirementPlacements(route)) {
			const available = servicesType(application, placement.scopes);

			// A placement without services cannot provide a requirement; validation reports it.
			if (available) {
				checks.add(
					`\tRoutaServicesSatisfy<${JSON.stringify(placement.label)}, ${available}, ${contractTypeReference(placement.middleware.requiresServices)}>,`,
				);
			}
		}
	}

	if (checks.size === 0) {
		return "";
	}

	return `

/**
 * Each middleware that requires services, checked against the services available where it runs.
 * TypeScript reports a placement whose services do not satisfy the middleware's requirements.
 */
export type RoutaServiceRequirementChecks = [
${[...checks].join("\n")}
];

type RoutaServicesSatisfy<_TPlacement extends string, TAvailable extends TRequired, TRequired> = TAvailable;`;
}

/**
 * The type of a `ctx.services` mapping that combines scopes, or `undefined` when none applies.
 *
 * @param application - Whether the project declares application services
 * @param scopes - The route-file and method contracts, in the order they run
 */
function servicesType(
	application: boolean,
	scopes: ReadonlyArray<ServiceContractMetadata | undefined>,
): string | undefined {
	const parts = [
		...(application ? ["RoutaApplicationServices"] : []),
		...scopes.flatMap((scope) => (scope ? [contractTypeReference(scope)] : [])),
	];

	return parts.length > 0 ? `Readonly<${parts.join(" & ")}>` : undefined;
}

/**
 * Builds the aggregate context type contributed by all middleware across the project.
 *
 * @param routes - Route metadata used to collect provided context keys and their inferred types
 * @returns A TypeScript object type string for the combined context map, or `{ readonly __empty?: never }` when no context is provided
 */
function ctxByKeyType(
	routes: RouteMetadata[],
	authentication: AuthenticationMetadata | undefined,
): string {
	// Middleware that requires ctx.auth sees it before any requireAuth guard narrows it.
	const ctx = new Map<string, string>(authentication ? [["auth", "RoutaAuth"]] : []);

	for (const route of routes) {
		const chains = [route.middleware, ...Object.values(route.methodMiddleware)];

		for (const chain of chains) {
			for (const middleware of chain) {
				for (const key of middleware.provides) {
					ctx.set(key, middleware.providesTypes[key] ?? "unknown");
				}
			}
		}
	}

	if (ctx.size === 0) {
		return "{ readonly __empty?: never }";
	}

	return `{\n${Array.from(ctx.entries())
		.sort(([left], [right]) => compareText(left, right))
		.map(([key, type]) => `\t${JSON.stringify(key)}: ${indentType(type, 1)};`)
		.join("\n")}\n}`;
}

/**
 * Builds the route context map for all HTTP methods.
 *
 * @param route - The route metadata to describe.
 * @returns A TypeScript object type mapping each HTTP method to its context type.
 */
function routeMethodCtxMap(
	route: RouteMetadata,
	application: boolean,
	authentication: AuthenticationMetadata | undefined,
): string {
	const methods: string[] = [];

	for (const method of ["get", "post", "put", "patch", "delete", "head"]) {
		methods.push(
			`\t\t${method}: ${routeCtxTypeNameForMiddleware(route, method, application, authentication)};`,
		);
	}

	return `{\n${methods.join("\n")}\n\t}`;
}

/**
 * Builds the context type for a route method's middleware chain. A route file that declares
 * services also types the handler's `ctx.services`, combining every scope the method runs.
 *
 * @param route - The route metadata to inspect
 * @param method - The HTTP method whose middleware chain is used when present
 * @returns A TypeScript object type for the middleware-provided context keys
 */
function routeCtxTypeNameForMiddleware(
	route: RouteMetadata,
	method: string,
	application: boolean,
	authentication: AuthenticationMetadata | undefined,
): string {
	const chain = route.methodMiddleware[method] ?? route.middleware;
	const services =
		route.services
		&& servicesType(application, [route.services.routeFile, route.services.methods?.[method]]);

	return ctxObjectType(chain, services, authType(chain, authentication));
}

/**
 * The type of `ctx.auth` after a middleware chain, or `undefined` without authentication: anonymous
 * or authenticated, or authenticated through the schemes every requireAuth guard in it allows.
 */
function authType(
	chain: readonly MiddlewareMetadata[],
	authentication: AuthenticationMetadata | undefined,
): string | undefined {
	if (!authentication) {
		return undefined;
	}

	if (!chain.some((item) => item.authentication)) {
		return "RoutaAuth";
	}

	const allowed = allowedSchemes(chain, authentication);
	return `import("@routa-ts/core").AuthenticatedAuthContext<${allowed.map((name) => JSON.stringify(name)).join(" | ") || "never"}, RoutaPrincipal>`;
}

/**
 * Builds a context object type from the keys a middleware chain provides, its `auth` type, and a
 * `services` type.
 *
 * @returns A TypeScript object type nested two levels deep in the generated map
 */
function ctxObjectType(
	chain: readonly MiddlewareMetadata[],
	services: string | undefined,
	auth?: string,
): string {
	const ctx = new Map<string, string>();

	for (const middleware of chain) {
		for (const key of middleware.provides) {
			ctx.set(key, middleware.providesTypes[key] ?? "unknown");
		}
	}

	if (ctx.size === 0 && !services && !auth) {
		return "{ readonly __empty?: never }";
	}

	return `{\n${[
		...Array.from(ctx.entries())
			.sort(([left], [right]) => compareText(left, right))
			.map(([key, type]) => `\t\t\t${JSON.stringify(key)}: ${indentType(type, 3)};`),
		...(auth ? [`\t\t\treadonly "auth": ${auth};`] : []),
		...(services ? [`\t\t\treadonly "services": ${services};`] : []),
	].join("\n")}\n\t\t}`;
}

/**
 * Indents each line of a type string.
 *
 * @param type - The type text to indent
 * @param tabs - The number of tab characters to prepend to each line after the first
 * @returns The type text with newline-separated lines indented
 */
function indentType(type: string, tabs: number): string {
	const indentation = "\t".repeat(tabs);
	return type.replaceAll("\n", `\n${indentation}`);
}

/**
 * Builds the generated context type name for a route path.
 *
 * @param route - The route metadata used to derive the name
 * @returns The route context type name
 */
function routeCtxTypeName(route: RouteMetadata): string {
	const suffix = route.path === "/" ? "Root" : pascalCase(route.path);
	return `${suffix}Ctx`;
}

/**
 * Converts a string to PascalCase.
 *
 * @param value - The input string
 * @returns The PascalCase form of `value`, or `"Route"` when no alphanumeric characters are present
 */
function pascalCase(value: string): string {
	const text = value.replaceAll(/[^a-zA-Z0-9]+/g, " ").trim();

	if (!text) {
		return "Route";
	}

	return text
		.split(/\s+/)
		.map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
		.join("");
}

/**
 * Appends captured output to a list of lines.
 *
 * @param lines - The lines to join.
 * @param output - Additional output to append after the joined lines.
 * @returns The combined text with a trailing newline.
 */
function appendOutput(lines: string[], output?: string): string {
	const base = `${lines.join("\n")}\n`;

	if (!output) {
		return base;
	}

	return `${base}${output.endsWith("\n") ? output : `${output}\n`}`;
}

/**
 * Formats diagnostics into a newline-separated report.
 *
 * @param diagnostics - Diagnostics to format
 * @returns The formatted diagnostic report
 */
export function formatDiagnostics(diagnostics: Diagnostic[]): string {
	return diagnostics
		.map((diagnostic) => {
			const severity = diagnostic.severity === "warning" ? "Warning: " : "";
			const location = diagnostic.file ? `${diagnostic.file}: ` : "";
			const suggestion = diagnostic.suggestion ? `\nSuggestion: ${diagnostic.suggestion}` : "";
			return `${severity}${diagnostic.code}: ${location}${diagnostic.message}${suggestion}`;
		})
		.join("\n");
}

/**
 * Recursively lists all files under a directory.
 *
 * Symlink cycles are skipped by tracking visited real paths.
 *
 * @param dir - The directory to traverse
 * @param visited - Real paths already visited during this walk
 * @returns The full paths of all files found under `dir`
 */
function walk(dir: string, visited = new Set<string>()): string[] {
	let realDir: string;

	try {
		realDir = realpathSync(dir);
	} catch {
		return [];
	}

	if (visited.has(realDir)) {
		return [];
	}

	visited.add(realDir);

	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const file = join(dir, entry.name);

		if (entry.isSymbolicLink()) {
			let stats: ReturnType<typeof statSync>;

			try {
				stats = statSync(file);
			} catch {
				return [];
			}

			return stats.isDirectory() ? walk(file, visited) : [file];
		}

		return entry.isDirectory() ? walk(file, visited) : [file];
	});
}
